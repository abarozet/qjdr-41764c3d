var PREFIX = 'qjdr-';
var CACHE = PREFIX + VERSION;

function scopeURL(path) { return new URL(path, self.registration.scope).href; }

self.addEventListener('install', function (event) {
  event.waitUntil(caches.open(CACHE).then(function (cache) {
    // cache: 'reload' bypasses the HTTP cache so a new version never stores stale files.
    return cache.addAll(PRECACHE.map(function (p) { return new Request(scopeURL(p), { cache: 'reload' }); }));
  }));
  // No skipWaiting() here: an update waits for the user (toast « Recharger »).
});

self.addEventListener('activate', function (event) {
  event.waitUntil(caches.keys().then(function (keys) {
    return Promise.all(keys.filter(function (k) { return k.indexOf(PREFIX) === 0 && k !== CACHE; }).map(function (k) { return caches.delete(k); }));
  }).then(function () { return self.clients.claim(); }));
});

self.addEventListener('message', function (event) {
  if (event.data && event.data.type === 'SKIP_WAITING') self.skipWaiting();
});

self.addEventListener('fetch', function (event) {
  var req = event.request;
  if (req.method !== 'GET') return;
  var url = new URL(req.url);
  var scope = new URL(self.registration.scope);
  if (url.origin !== scope.origin || url.pathname.indexOf(scope.pathname) !== 0) return;
  var rel = url.pathname.slice(scope.pathname.length);
  if (rel === '' || rel.slice(-1) === '/') rel += 'index.html';
  var key = scopeURL(rel); // query strings are ignored (e.g. the Aide tab's ?t= probe)
  var isNav = req.mode === 'navigate';
  if (isNav) event.waitUntil(self.registration.update().catch(function () { /* offline */ }));

  event.respondWith(caches.open(CACHE).then(function (cache) {
    return cache.match(key).then(function (hit) {
      if (hit) return hit;
      return fetch(req).then(function (res) {
        if (res && res.ok && res.type === 'basic') cache.put(key, res.clone());
        return res;
      }).catch(function (err) {
        if (isNav) return cache.match(scopeURL('index.html')).then(function (r) { if (r) return r; throw err; });
        throw err;
      });
    });
  }));
});
