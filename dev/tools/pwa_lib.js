// Shared logic of dev/tools/build_pwa.mjs and dev/tests/sync.test.js (CommonJS,
// pure Node): list of the files of the web app, desktop HTML copy, precache
// version, generated block of sw.js.
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');

const APP = path.join(__dirname, '..', '..', 'QuestionnaireJDR');
const DESKTOP_HTML = 'Questionnaire JDR.html';
const SW = 'sw.js';

// Never shipped / never precached: hidden and OS files, editor leftovers, dev folders.
const EXCLUDE = [/(^|\/)\.[^/]*$/, /(^|\/)Thumbs\.db$/i, /(^|\/)desktop\.ini$/i, /~$/, /\.(map|bak|tmp|log|orig)$/i,
  /(^|\/)(node_modules|dev|tests|e2e|screenshots)(\/|$)/];

function isExcluded(rel) { return EXCLUDE.some((re) => re.test(rel)); }

/** All distributable files of QuestionnaireJDR/ (relative, '/'-separated, sorted). */
function listAppFiles(app = APP) {
  const out = [];
  (function walk(dir) {
    for (const name of fs.readdirSync(dir).sort()) {
      const full = path.join(dir, name);
      const rel = path.relative(app, full).split(path.sep).join('/');
      if (isExcluded(rel)) continue;
      if (fs.statSync(full).isDirectory()) walk(full);
      else out.push(rel);
    }
  })(app);
  return out.sort();
}

/** Files precached by the service worker: everything except sw.js itself. */
function precacheFiles(app = APP) {
  return listAppFiles(app).filter((f) => f !== SW);
}

/** URL-encode each path segment (spaces, accents) the way the browser requests it. */
function toURL(rel) { return rel.split('/').map(encodeURIComponent).join('/'); }

const BEGIN = '/* BEGIN GENERATED by dev/tools/build_pwa.mjs — do not edit by hand */';
const END = '/* END GENERATED */';

function swBlock(version, files) {
  return BEGIN + '\n' +
    'var VERSION = ' + JSON.stringify(version) + ';\n' +
    'var PRECACHE = [\n' + files.map((f) => '  ' + JSON.stringify(toURL(f))).join(',\n') + '\n];\n' +
    END;
}

function applySwBlock(swText, block) {
  const a = swText.indexOf(BEGIN), b = swText.indexOf(END);
  if (a < 0 || b < a) throw new Error('sw.js: GENERATED markers not found');
  return swText.slice(0, a) + block + swText.slice(b + END.length);
}

/** Reads VERSION and PRECACHE from sw.js. */
function readSwBlock(swText) {
  const a = swText.indexOf(BEGIN), b = swText.indexOf(END);
  if (a < 0 || b < a) return null;
  const code = swText.slice(a + BEGIN.length, b);
  const sandbox = {};
  require('node:vm').runInNewContext(code + '\nthis.VERSION = VERSION; this.PRECACHE = PRECACHE;', sandbox);
  return { version: sandbox.VERSION, precache: Array.from(sandbox.PRECACHE) };
}

/**
 * The desktop entry point (double-click over file://) is generated from
 * index.html: same page, plus a "generated" notice, minus the web manifest
 * (useless over file://, where Chrome would only log a fetch error).
 */
function desktopHtmlFrom(indexHtml) {
  const notice = '<!-- GENERATED from index.html by dev/tools/build_pwa.mjs: edit index.html, then run the tool. -->\n';
  let out = indexHtml.replace(/^(<!DOCTYPE html>\r?\n)/i, '$1' + notice);
  if (out === indexHtml) out = notice + indexHtml;
  return out.replace(/^<link rel="manifest"[^>]*>\r?\n/m, '');
}

/** Expected content of the generated files, computed from the sources on disk. */
function expectedOutputs(app = APP) {
  const index = fs.readFileSync(path.join(app, 'index.html'), 'utf8');
  const desktop = desktopHtmlFrom(index);
  // the version must account for the desktop copy as it will be written
  const files = Array.from(new Set(precacheFiles(app).concat([DESKTOP_HTML]))).sort();
  const h = crypto.createHash('sha256');
  for (const f of files) {
    h.update(f + '\0');
    h.update(f === DESKTOP_HTML ? Buffer.from(desktop, 'utf8') : fs.readFileSync(path.join(app, f)));
    h.update('\0');
  }
  const version = h.digest('hex').slice(0, 12);
  const sw = applySwBlock(fs.readFileSync(path.join(app, SW), 'utf8'), swBlock(version, files));
  return { desktop, sw, version, files };
}

module.exports = { APP, DESKTOP_HTML, SW, EXCLUDE, isExcluded, listAppFiles, precacheFiles, toURL, swBlock, applySwBlock, readSwBlock, desktopHtmlFrom, expectedOutputs };
